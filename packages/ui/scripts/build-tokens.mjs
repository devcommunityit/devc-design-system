// Generates every token output from the single source in ../tokens.
// Run: npm run tokens   (Node >= 22.18 / 24: executes the shared TypeScript via type stripping)
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createTonalPalettes, resolveRoles, STANDARD_TONES } from '../src/theme/palette.ts';
import { contrastRatio } from '../src/theme/contrast.ts';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const repoRoot = resolve(root, '../..');
const readJson = (p) => JSON.parse(readFileSync(resolve(root, p), 'utf8'));

const base = readJson('tokens/base.tokens.json');
const densities = {
  comfortable: readJson('tokens/density.comfortable.tokens.json'),
  compact: readJson('tokens/density.compact.tokens.json'),
};
const colorConfig = readJson('tokens/color.config.json');
const lookConfig = readJson('tokens/look.config.json');
const PREFIX = 'dc';
const HEADER = '/* AUTO-GENERATED by scripts/build-tokens.mjs from packages/ui/tokens. Do not edit. */\n';

// ---------- DTCG helpers ----------
const isToken = (node) => node && typeof node === 'object' && '$value' in node;

function walk(node, path = [], inheritedType, out = []) {
  if (!node || typeof node !== 'object') return out;
  const type = node.$type ?? inheritedType;
  if (isToken(node)) {
    out.push({ path, type, value: node.$value, extensions: node.$extensions, description: node.$description });
    return out;
  }
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    walk(child, [...path, key], type, out);
  }
  return out;
}

const index = new Map(walk(base).map((t) => [t.path.join('.'), t]));

function resolveRef(value, seen = new Set()) {
  if (typeof value === 'string' && /^\{[^}]+\}$/.test(value)) {
    const ref = value.slice(1, -1);
    if (seen.has(ref)) throw new Error(`Circular token reference: ${ref}`);
    const target = index.get(ref);
    if (!target) throw new Error(`Unknown token reference: ${ref}`);
    seen.add(ref);
    return resolveRef(target.value, seen);
  }
  return value;
}

const varName = (path) => `--${PREFIX}-${path.join('-')}`;
const fmtNumber = (n) => String(Math.round(n * 10000) / 10000);

function toCss(token, value = resolveRef(token.value)) {
  const fluid = token.extensions?.['dev.dc.fluid'];
  if (fluid) return fluid;
  switch (token.type) {
    case 'dimension':
    case 'duration':
      return `${fmtNumber(value.value)}${value.unit}`;
    case 'fontFamily':
      return value.map((f) => (/[\s]/.test(f) ? `"${f}"` : f)).join(', ');
    case 'cubicBezier':
      return `cubic-bezier(${value.join(', ')})`;
    case 'shadow':
      return value
        .map((s) => `${s.inset ? 'inset ' : ''}${toCss({ type: 'dimension' }, s.offsetX)} ${toCss({ type: 'dimension' }, s.offsetY)} ${toCss({ type: 'dimension' }, s.blur)} ${toCss({ type: 'dimension' }, s.spread)} ${s.color}`)
        .join(', ');
    case 'number':
      if (token.path?.[0] === 'state') return `${fmtNumber(value * 100)}%`;
      return fmtNumber(value);
    default:
      return String(value);
  }
}

const baseTokens = walk(base).filter((t) => t.path[0] !== 'breakpoint');
const breakpoints = Object.fromEntries(
  walk(base).filter((t) => t.path[0] === 'breakpoint').map((t) => [t.path[1], t.value.value]),
);

// ---------- Colors ----------
const roles = colorConfig.roles;
const roleNames = Object.keys(roles);
const presetNames = Object.keys(colorConfig.presets);
const seedsFor = (preset) => ({ brand: preset.brand, ...(preset.tertiary ? { tertiary: preset.tertiary } : {}), ...colorConfig.feedback });

const presetColors = {};
const presetPalettes = {};
for (const name of presetNames) {
  const palettes = createTonalPalettes(seedsFor(colorConfig.presets[name]), colorConfig.palettes);
  presetPalettes[name] = palettes;
  presetColors[name] = {
    light: resolveRoles(palettes, roles, 'light'),
    dark: resolveRoles(palettes, roles, 'dark'),
  };
}

// Contrast gate: fail the build if a preset breaks a documented pair.
const contrastFailures = [];
for (const name of presetNames) {
  for (const scheme of ['light', 'dark']) {
    for (const [fg, bg, min] of colorConfig.contrastPairs.pairs) {
      const ratio = contrastRatio(presetColors[name][scheme][fg], presetColors[name][scheme][bg]);
      if (ratio === null || ratio < min) contrastFailures.push(`${name}/${scheme}: ${fg} on ${bg} = ${ratio?.toFixed(2)} < ${min}`);
    }
  }
}
if (contrastFailures.length) {
  console.error('Contrast check failed:\n' + contrastFailures.join('\n'));
  process.exit(1);
}

const colorVar = (role) => `--${PREFIX}-color-${role.replace(/\./g, '-')}`;
const decls = (entries, indent = '  ') => entries.map(([k, v]) => `${indent}${k}: ${v};`).join('\n');
const colorDecls = (colors, indent) => decls(roleNames.map((r) => [colorVar(r), colors[r]]), indent);

// ---------- Look (CSS expressions referencing other tokens) ----------
const knownRefs = new Set([
  ...baseTokens.map((t) => t.path.join('.')),
  ...roleNames.map((r) => `color.${r}`),
  ...Object.keys(lookConfig.gradient).map((k) => `gradient.${k}`),
]);
const refToVar = (expr) =>
  expr.replace(/\{([a-z0-9.-]+)\}/g, (_, ref) => {
    if (!knownRefs.has(ref)) throw new Error(`look.config.json: unknown token reference {${ref}}`);
    return `var(--${PREFIX}-${ref.replace(/\./g, '-')})`;
  });
const lookNames = Object.keys(lookConfig.looks);
const gradientDecls = Object.entries(lookConfig.gradient).map(([k, v]) => [`--${PREFIX}-gradient-${k}`, refToVar(v)]);
const lookDecls = (look, indent) => decls(Object.entries(lookConfig.looks[look]).map(([k, v]) => [`--${PREFIX}-look-${k}`, refToVar(v)]), indent);

// ---------- CSS ----------
const T = `[data-${PREFIX}-theme]`;
const densityDecls = (d) => decls(walk(densities[d]).map((t) => [varName(t.path), toCss(t)]));
const defaultPreset = colorConfig.defaultPreset;

let css = HEADER;
css += `/* Tokens are scoped to elements rendered by ThemeProvider (or carrying data-${PREFIX}-theme). Zero specificity via :where(). */\n`;
css += `:where(${T}) {\n${decls(baseTokens.map((t) => [varName(t.path), toCss(t)]))}\n${densityDecls('comfortable')}\n${colorDecls(presetColors[defaultPreset].light)}\n}\n\n`;
css += `:where(${T}[data-${PREFIX}-density="compact"]) {\n${densityDecls('compact')}\n}\n\n`;
for (const name of presetNames) {
  css += `:where(${T}[data-${PREFIX}-palette="${name}"]) {\n${colorDecls(presetColors[name].light)}\n}\n`;
  css += `:where(${T}[data-${PREFIX}-palette="${name}"][data-${PREFIX}-scheme="dark"]) {\n${colorDecls(presetColors[name].dark)}\n}\n`;
  css += `@media (prefers-color-scheme: dark) {\n  :where(${T}[data-${PREFIX}-palette="${name}"][data-${PREFIX}-scheme="system"]) {\n${colorDecls(presetColors[name].dark, '    ')}\n  }\n}\n\n`;
}
// Inline custom themes: ThemeProvider sets --dc-light-color-* / --dc-dark-color-* on the element.
const mapTo = (scheme, indent) => decls(roleNames.map((r) => [colorVar(r), `var(${colorVar(r).replace(`--${PREFIX}-`, `--${PREFIX}-${scheme}-`)})`]), indent);
css += `/* Custom themes applied inline by ThemeProvider (no <style> injection, CSP friendly). */\n`;
css += `:where(${T}[data-${PREFIX}-palette-source="inline"]) {\n${mapTo('light', '  ')}\n}\n`;
css += `:where(${T}[data-${PREFIX}-palette-source="inline"][data-${PREFIX}-scheme="dark"]) {\n${mapTo('dark', '  ')}\n}\n`;
css += `@media (prefers-color-scheme: dark) {\n  :where(${T}[data-${PREFIX}-palette-source="inline"][data-${PREFIX}-scheme="system"]) {\n${mapTo('dark', '    ')}\n  }\n}\n\n`;
css += `/* Look: standard by default, expressive adds two-tone gradients, glow and rounder shapes. */\n`;
css += `:where(${T}) {\n${decls(gradientDecls)}\n${lookDecls(lookConfig.defaultLook)}\n}\n`;
for (const look of lookNames.filter((l) => l !== lookConfig.defaultLook)) css += `:where(${T}[data-${PREFIX}-look="${look}"]) {\n${lookDecls(look)}\n}\n`;
css += `\n`;
css += `:where(${T}[data-${PREFIX}-scheme="light"]) { color-scheme: light; }\n`;
css += `:where(${T}[data-${PREFIX}-scheme="dark"]) { color-scheme: dark; }\n`;
css += `:where(${T}[data-${PREFIX}-scheme="system"]) { color-scheme: light dark; }\n\n`;
css += `@media (prefers-reduced-motion: reduce) {\n  :where(${T}) {\n    --${PREFIX}-motion-duration-fast: 0ms;\n    --${PREFIX}-motion-duration-normal: 0ms;\n    --${PREFIX}-motion-duration-slow: 0ms;\n  }\n}\n\n`;
css += `@media (forced-colors: active) {\n  :where(${T}) {\n    --${PREFIX}-color-focus-ring: Highlight;\n    --${PREFIX}-color-border-strong: CanvasText;\n    --${PREFIX}-color-border-default: CanvasText;\n    --${PREFIX}-color-border-selected: Highlight;\n${decls(gradientDecls.map(([k]) => [k, 'none']), '    ')}\n    --${PREFIX}-look-fill-primary: none;\n    --${PREFIX}-look-fill-tonal: none;\n    --${PREFIX}-look-shadow-primary: none;\n  }\n}\n`;

mkdirSync(resolve(root, 'src/styles/generated'), { recursive: true });
writeFileSync(resolve(root, 'src/styles/generated/tokens.css'), css);

// ---------- TypeScript ----------
const cssVarMap = Object.fromEntries(baseTokens.map((t) => [t.path.join('.'), toCss(t)]));
const densityMap = Object.fromEntries(
  Object.entries(densities).map(([d, src]) => [d, Object.fromEntries(walk(src).map((t) => [t.path.join('.'), toCss(t)]))]),
);
const presetMeta = Object.fromEntries(presetNames.map((n) => [n, { label: colorConfig.presets[n].label, brand: colorConfig.presets[n].brand, ...(colorConfig.presets[n].tertiary ? { tertiary: colorConfig.presets[n].tertiary } : {}), description: colorConfig.presets[n].description }]));

const ts = `${HEADER.replace('/*', '/*').trim()}
/* eslint-disable */
export const TOKEN_PREFIX = ${JSON.stringify(PREFIX)} as const;

export const COLOR_ROLES = ${JSON.stringify(roleNames, null, 2)} as const;
export type ColorRole = (typeof COLOR_ROLES)[number];

export const ROLE_SPECS = ${JSON.stringify(roles, null, 2)} as const;

export const PRESET_NAMES = ${JSON.stringify(presetNames)} as const;
export type PresetName = (typeof PRESET_NAMES)[number];
export const DEFAULT_PRESET: PresetName = ${JSON.stringify(defaultPreset)};

export const PRESET_META: Record<PresetName, { label: { it: string; en: string }; brand: string; tertiary?: string; description: string }> = ${JSON.stringify(presetMeta, null, 2)};

export const PRESET_COLORS: Record<PresetName, { light: Record<ColorRole, string>; dark: Record<ColorRole, string> }> = ${JSON.stringify(presetColors, null, 2)};

export const FEEDBACK_SEEDS = ${JSON.stringify(colorConfig.feedback, null, 2)} as const;
export const PALETTE_RULES = ${JSON.stringify(Object.fromEntries(Object.entries(colorConfig.palettes).filter(([k]) => !k.startsWith('$'))), null, 2)} as const;

export const CONTRAST_PAIRS: ReadonlyArray<readonly [ColorRole, ColorRole, number]> = ${JSON.stringify(colorConfig.contrastPairs.pairs)};

/** Non-color tokens: dotted path -> CSS value. CSS variable = --${PREFIX}-<path with dashes>. */
export const BASE_TOKENS = ${JSON.stringify(cssVarMap, null, 2)} as const;
export type BaseTokenName = keyof typeof BASE_TOKENS;

export const DENSITY_TOKENS = ${JSON.stringify(densityMap, null, 2)} as const;
export type Density = keyof typeof DENSITY_TOKENS;

/** Visual style, independent of palette and density. Values are CSS expressions on --${PREFIX}-look-*. */
export const LOOK_TOKENS = ${JSON.stringify(Object.fromEntries(lookNames.map((l) => [l, Object.fromEntries(Object.entries(lookConfig.looks[l]).map(([k, v]) => [k, refToVar(v)]))])), null, 2)} as const;
export type Look = keyof typeof LOOK_TOKENS;
export const LOOK_NAMES = ${JSON.stringify(lookNames)} as const;
export const DEFAULT_LOOK: Look = ${JSON.stringify(lookConfig.defaultLook)};
/** Gradients always available as --${PREFIX}-gradient-*. */
export const GRADIENT_TOKENS = ${JSON.stringify(Object.fromEntries(gradientDecls.map(([k, v]) => [k.replace(`--${PREFIX}-gradient-`, ""), v])), null, 2)} as const;

/** Mobile-first min-width breakpoints in CSS px. Not available as CSS variables (invalid in @media). */
export const breakpoints = ${JSON.stringify(breakpoints, null, 2)} as const;
`;
mkdirSync(resolve(root, 'src/tokens'), { recursive: true });
writeFileSync(resolve(root, 'src/tokens/generated.ts'), ts);

// ---------- DTCG exports (Figma / design tools) ----------
mkdirSync(resolve(repoRoot, 'design/figma'), { recursive: true });
const setPath = (obj, path, value) => {
  let cur = obj;
  path.slice(0, -1).forEach((k) => (cur = cur[k] ??= {}));
  cur[path.at(-1)] = value;
};
const usedTones = [...new Set([...STANDARD_TONES, ...Object.values(roles).flatMap((r) => [r.light, r.dark])])].sort((a, b) => a - b);

// 1) Spec-compliant DTCG (2025.10): colors as objects, dimensions as {value, unit}.
const hexToDtcg = (hex) => {
  const n = Number.parseInt(hex.slice(1, 7), 16);
  const comps = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((c) => Math.round((c / 255) * 10000) / 10000);
  const alpha = hex.length === 9 ? Math.round((Number.parseInt(hex.slice(7), 16) / 255) * 1000) / 1000 : 1;
  return { colorSpace: 'srgb', components: comps, alpha, hex: hex.slice(0, 7) };
};
const dtcg = { $description: '@dev-community/ui design tokens (DTCG). Generated — do not edit.', base: {}, density: {}, palette: {}, color: {} };
for (const t of walk(base)) setPath(dtcg.base, t.path, { $type: t.type, $value: t.type === 'shadow' ? t.value.map((s) => ({ ...s, color: hexToDtcg(s.color) })) : t.value, ...(t.extensions ? { $extensions: t.extensions } : {}) });
for (const [d, src] of Object.entries(densities)) for (const t of walk(src)) setPath(dtcg.density, [d, ...t.path], { $type: t.type, $value: t.value });
for (const name of presetNames) {
  for (const p of Object.keys(presetPalettes[name])) for (const tone of usedTones) setPath(dtcg.palette, [name, p, String(tone)], { $type: 'color', $value: hexToDtcg(presetPalettes[name][p](tone)) });
  for (const scheme of ['light', 'dark']) for (const role of roleNames) {
    const spec = roles[role];
    setPath(dtcg.color, [name, scheme, ...role.split('.')], { $type: 'color', $value: hexToDtcg(presetColors[name][scheme][role]), $extensions: { 'dev.dc.alias': `{palette.${name}.${spec.palette}.${spec[scheme]}}`, 'dev.dc.cssVar': colorVar(role) } });
  }
}
writeFileSync(resolve(repoRoot, 'design/figma/tokens.dtcg.json'), JSON.stringify(dtcg, null, 2));

// 2) Tokens Studio flavor (string values + aliases), one set per mode, plus $themes.json.
const tsValue = (t) => {
  const v = t.value;
  if (typeof v === 'string' && v.startsWith('{')) return v;
  switch (t.type) {
    case 'dimension': case 'duration': return `${v.value}${v.unit}`;
    case 'fontFamily': return v.join(', ');
    case 'cubicBezier': return v;
    case 'shadow': return v.map((s) => ({ color: s.color, x: `${s.offsetX.value}`, y: `${s.offsetY.value}`, blur: `${s.blur.value}`, spread: `${s.spread.value}`, type: 'dropShadow' }));
    default: return v;
  }
};
const studioType = (type) => ({ dimension: 'dimension', duration: 'other', fontFamily: 'fontFamilies', fontWeight: 'fontWeights', number: 'number', shadow: 'boxShadow', cubicBezier: 'other', color: 'color' }[type] ?? 'other');
const sets = {};
const baseSet = {};
for (const t of walk(base)) setPath(baseSet, t.path, { $type: studioType(t.type), $value: tsValue(t) });
sets['base'] = baseSet;
for (const [d, src] of Object.entries(densities)) {
  const s = {};
  for (const t of walk(src)) setPath(s, t.path, { $type: 'dimension', $value: tsValue(t) });
  sets[`density/${d}`] = s;
}
for (const name of presetNames) {
  const pal = {};
  for (const p of Object.keys(presetPalettes[name])) for (const tone of usedTones) setPath(pal, ['palette', p, String(tone)], { $type: 'color', $value: presetPalettes[name][p](tone) });
  sets[`palette/${name}`] = pal;
}
for (const scheme of ['light', 'dark']) {
  const s = {};
  for (const role of roleNames) setPath(s, ['color', ...role.split('.')], { $type: 'color', $value: `{palette.${roles[role].palette}.${roles[role][scheme]}}` });
  sets[`scheme/${scheme}`] = s;
}
const studioDir = resolve(repoRoot, 'design/figma/tokens-studio');
rmSync(studioDir, { recursive: true, force: true });
for (const [name, set] of Object.entries(sets)) {
  const file = resolve(studioDir, `${name}.json`);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, JSON.stringify(set, null, 2));
}
const themes = [];
for (const name of presetNames) for (const scheme of ['light', 'dark']) for (const d of Object.keys(densities)) {
  themes.push({ id: `${name}-${scheme}-${d}`, name: `${name} / ${scheme} / ${d}`, group: 'dc', selectedTokenSets: { base: 'enabled', [`density/${d}`]: 'enabled', [`palette/${name}`]: 'source', [`scheme/${scheme}`]: 'enabled' } });
}
writeFileSync(resolve(studioDir, '$themes.json'), JSON.stringify(themes, null, 2));
writeFileSync(resolve(studioDir, '$metadata.json'), JSON.stringify({ tokenSetOrder: Object.keys(sets) }, null, 2));

console.log(`Tokens generated: ${baseTokens.length} base, ${roleNames.length} color roles x ${presetNames.length} presets x 2 schemes, ${Object.keys(densities).length} densities, ${lookNames.length} looks.`);
