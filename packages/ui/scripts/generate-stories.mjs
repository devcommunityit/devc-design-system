/**
 * Generates Storybook CSF files from the shared documentation sources
 * (`*.meta.ts` + `*.examples.tsx`), so Storybook and the docs site never diverge.
 * Output: .storybook/generated (git-ignored, regenerated before every Storybook run).
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, '.storybook', 'generated');
const sources = [join(root, 'src', 'components'), join(root, 'src', 'patterns')];

const CATEGORY_LABELS = {
  layout: 'Layout',
  typography: 'Tipografia',
  actions: 'Azioni',
  navigation: 'Navigazione',
  forms: 'Form',
  data: 'Contenuti e dati',
  charts: 'Grafici',
  dashboard: 'Dashboard',
  ai: 'AI',
  website: 'Gestione siti',
  community: 'Community',
  editor: 'Editor',
  feedback: 'Feedback',
  overlay: 'Overlay',
  patterns: 'Pattern',
};

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
}

const toImport = (from, file) => {
  const rel = relative(from, file).split(sep).join('/').replace(/\.tsx?$/, '');
  return rel.startsWith('.') ? rel : `./${rel}`;
};

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

let count = 0;
const errors = [];
for (const metaFile of sources.flatMap(walk).filter((f) => f.endsWith('.meta.ts'))) {
  const meta = readFileSync(metaFile, 'utf8');
  const name = meta.match(/^ {2}name: (['"])(.*?)\1/m)?.[2];
  const slug = meta.match(/^ {2}slug: (['"])(.*?)\1/m)?.[2];
  const category = meta.match(/^ {2}category: (['"])(.*?)\1/m)?.[2];
  if (!name || !slug || !category || !(category in CATEGORY_LABELS)) {
    errors.push(`${relative(root, metaFile)}: cannot read name/slug/category`);
    continue;
  }
  const examplesFile = metaFile.replace(/\.meta\.ts$/, '.examples.tsx');
  // Example names come from the meta `examples` list (the documented, display-ordered set).
  const examplesStart = meta.search(/^ {2}examples: \[/m);
  const examplesBlock = examplesStart < 0 ? '' : meta.slice(examplesStart, meta.indexOf('\n  status:', examplesStart));
  const titles = new Map(
    [...examplesBlock.matchAll(/\{\s*name:\s*(['"])(\w+)\1,\s*title:\s*(['"])((?:\\.|[^\\])*?)\3/g)].map((m) => [m[2], m[4].replace(/\\(['"\\])/g, '$1')]),
  );
  const examples = [...titles.keys()];
  let source;
  try {
    source = readFileSync(examplesFile, 'utf8');
  } catch {
    errors.push(`${relative(root, metaFile)}: missing ${relative(root, examplesFile)}`);
    continue;
  }
  if (examples.length === 0) {
    errors.push(`${relative(root, metaFile)}: no examples listed`);
    continue;
  }
  const missing = examples.filter((ex) => !new RegExp(`^export (function|const) ${ex}\\b`, 'm').test(source));
  if (missing.length) {
    errors.push(`${relative(root, examplesFile)}: missing exports ${missing.join(', ')}`);
    continue;
  }

  const file = join(outDir, `${slug}.stories.tsx`);
  const lines = [
    '// Generated by scripts/generate-stories.mjs from the .meta.ts/.examples.tsx sources. Do not edit.',
    "import type { Meta, StoryObj } from '@storybook/react-vite';",
    `import { doc } from '${toImport(outDir, metaFile)}';`,
    `import * as Examples from '${toImport(outDir, examplesFile)}';`,
    '',
    `const meta = { title: '${CATEGORY_LABELS[category]}/${name.replace(/'/g, "\\'")}', parameters: { componentDoc: doc } } satisfies Meta;`,
    'export default meta;',
    'type Story = StoryObj<typeof meta>;',
    '',
    ...examples.map((ex) => `export const ${ex}: Story = { name: ${JSON.stringify(titles.get(ex))}, render: () => <Examples.${ex} /> };`),
    '',
  ];
  writeFileSync(file, lines.join('\n'));
  count += 1;
}

if (errors.length) {
  console.error(`generate-stories: ${errors.length} problem(s)\n  ${errors.join('\n  ')}`);
  process.exit(1);
}
console.log(`generate-stories: ${count} story files in ${relative(root, outDir)}`);
