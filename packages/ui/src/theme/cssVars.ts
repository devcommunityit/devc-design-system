import { COLOR_ROLES, TOKEN_PREFIX } from '../tokens/generated';
import type { Theme } from './types';

const P = TOKEN_PREFIX;

export const colorVar = (role: string) => `--${P}-color-${role.replace(/\./g, '-')}`;
export const tokenVar = (token: string) => `--${P}-${token.replace(/\./g, '-')}`;

/**
 * Inline custom properties for a custom theme (both schemes). Used by ThemeProvider
 * with `data-dc-palette-source="inline"`; the static stylesheet maps them to the active scheme.
 */
export function themeToStyle(theme: Theme): Record<string, string> {
  const style: Record<string, string> = {};
  for (const role of COLOR_ROLES) {
    const name = colorVar(role).slice(`--${P}-`.length);
    style[`--${P}-light-${name}`] = theme.colors.light[role];
    style[`--${P}-dark-${name}`] = theme.colors.dark[role];
  }
  for (const [token, value] of Object.entries(theme.tokens)) {
    if (value) style[tokenVar(token)] = value;
  }
  return style;
}

export interface ThemeToCssOptions {
  /** Attribute value used in `data-dc-palette`. Defaults to `theme.name`. */
  paletteName?: string;
}

/**
 * Static CSS for a theme, selected by `data-dc-palette="<name>"`. Suitable for strict CSP:
 * serve it as a stylesheet and use `<ThemeProvider theme={theme} themeStrategy="stylesheet">`.
 * All values come from a validated Theme, so no arbitrary CSS can be produced.
 */
export function themeToCss(theme: Theme, options: ThemeToCssOptions = {}): string {
  const name = options.paletteName ?? theme.name;
  if (!/^[a-z][a-z0-9-]*$/.test(name)) throw new Error(`Invalid palette name: ${name}`);
  const sel = `[data-${P}-theme][data-${P}-palette="${name}"]`;
  const block = (scheme: 'light' | 'dark', indent: string) =>
    COLOR_ROLES.map((role) => `${indent}${colorVar(role)}: ${theme.colors[scheme][role]};`).join('\n');
  const tokens = Object.entries(theme.tokens)
    .filter((entry): entry is [string, string] => typeof entry[1] === 'string')
    .map(([t, v]) => `  ${tokenVar(t)}: ${v};`)
    .join('\n');
  return [
    `/* ${theme.label} — generated by @devcommunityit/ui themeToCss() */`,
    `:where(${sel}) {\n${block('light', '  ')}${tokens ? `\n${tokens}` : ''}\n}`,
    `:where(${sel}[data-${P}-scheme="dark"]) {\n${block('dark', '  ')}\n}`,
    `@media (prefers-color-scheme: dark) {\n  :where(${sel}[data-${P}-scheme="system"]) {\n${block('dark', '    ')}\n  }\n}`,
    '',
  ].join('\n');
}
