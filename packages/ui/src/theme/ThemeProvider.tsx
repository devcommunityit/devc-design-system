import {
  createContext,
  forwardRef,
  useCallback,
  useContext,
  useEffect,
  useLayoutEffect,
  useMemo,
  useRef,
  useState,
  useSyncExternalStore,
  type CSSProperties,
  type HTMLAttributes,
  type ReactNode,
} from 'react';
import { UNSAFE_PortalProvider } from 'react-aria';
import { useLocale } from 'react-aria-components';
import { DEFAULT_LOOK, DEFAULT_PRESET, TOKEN_PREFIX, type Density, type Look, type PresetName } from '../tokens/generated';
import { getPreset, isPresetName } from './createTheme';
import { themeToStyle } from './cssVars';
import {
  DEFAULT_STORAGE_KEY,
  ThemePersistenceError,
  createLocalStorageAdapter,
  parsePreferences,
  serializePreferences,
  type ThemePreferences,
  type ThemeStorage,
} from './persistence';
import type { ResolvedScheme, Theme, ThemeMode } from './types';
import styles from './ThemeProvider.module.css';

const useIsoLayoutEffect = typeof document === 'undefined' ? useEffect : useLayoutEffect;

export type PersistedKey = 'mode' | 'theme' | 'density' | 'look';

export interface ThemePersistenceOptions {
  /** Storage adapter. Default: localStorage (accessed lazily, only in the browser). */
  storage?: ThemeStorage;
  /** Default `dc-theme`. */
  key?: string;
  /** Which preferences to persist. Default `['mode']`. */
  keys?: readonly PersistedKey[];
}

export interface ThemeContextValue {
  /** Preference: light, dark or system. */
  mode: ThemeMode;
  setMode: (mode: ThemeMode) => void;
  /** Effective scheme. With `system`, it is `light` during SSR and the first client render. */
  resolvedScheme: ResolvedScheme;
  theme: Theme;
  setTheme: (theme: PresetName | Theme) => void;
  density: Density;
  setDensity: (density: Density) => void;
  /** Visual style: `standard` (sober) or `expressive` (two-tone gradients, glow, rounder shapes). */
  look: Look;
  setLook: (look: Look) => void;
  /** Last persistence error, if any. */
  persistenceError: ThemePersistenceError | null;
  /** Element that receives portalled overlays for this provider. */
  portalContainer: HTMLElement | null;
}

const ThemeContext = createContext<ThemeContextValue | null>(null);

export interface ThemeProviderProps extends Omit<HTMLAttributes<HTMLDivElement>, 'children'> {
  children?: ReactNode;
  /** Controlled mode. When omitted, nested providers inherit their parent's mode. */
  mode?: ThemeMode;
  defaultMode?: ThemeMode;
  onModeChange?: (mode: ThemeMode) => void;
  /** Controlled palette: a preset name or a theme from `createTheme`. */
  theme?: PresetName | Theme;
  defaultTheme?: PresetName | Theme;
  onThemeChange?: (theme: Theme) => void;
  /** Custom themes that may be restored from persisted names. */
  themes?: readonly Theme[];
  density?: Density;
  defaultDensity?: Density;
  onDensityChange?: (density: Density) => void;
  /** Controlled look. Independent of palette and density; nested providers inherit it. */
  look?: Look;
  defaultLook?: Look;
  onLookChange?: (look: Look) => void;
  /** Opt-in persistence. `false` (default) never touches storage. */
  persistence?: boolean | ThemePersistenceOptions;
  onPersistenceError?: (error: ThemePersistenceError) => void;
  /**
   * `inline` (default) applies custom theme colors as inline custom properties.
   * `stylesheet` expects CSS generated by `themeToCss()` to be loaded (strict CSP).
   */
  themeStrategy?: 'inline' | 'stylesheet';
  /** Paint canvas background and default text color on the provider element. */
  surface?: boolean;
  /** Also mirror attributes on `<html>` (root provider only, opt-in). */
  applyToDocument?: boolean;
}

const darkQuery = '(prefers-color-scheme: dark)';
function subscribeScheme(callback: () => void) {
  if (typeof window === 'undefined' || !window.matchMedia) return () => {};
  const mql = window.matchMedia(darkQuery);
  mql.addEventListener('change', callback);
  return () => mql.removeEventListener('change', callback);
}
const getSchemeSnapshot = (): ResolvedScheme =>
  typeof window !== 'undefined' && window.matchMedia?.(darkQuery).matches ? 'dark' : 'light';
const getServerScheme = (): ResolvedScheme => 'light';

function toTheme(value: PresetName | Theme): Theme {
  return typeof value === 'string' ? getPreset(value) : value;
}

/**
 * Provides mode, palette, density and look to a subtree. Providers can be nested: unspecified
 * values are inherited. Portalled overlays rendered inside are mounted in a container that
 * carries the same theme attributes, so they match the provider they originate from.
 */
export const ThemeProvider = forwardRef<HTMLDivElement, ThemeProviderProps>(function ThemeProvider(props, ref) {
  const {
    children,
    mode: modeProp,
    defaultMode,
    onModeChange,
    theme: themeProp,
    defaultTheme,
    onThemeChange,
    themes,
    density: densityProp,
    defaultDensity,
    onDensityChange,
    look: lookProp,
    defaultLook,
    onLookChange,
    persistence = false,
    onPersistenceError,
    themeStrategy = 'inline',
    surface = false,
    applyToDocument = false,
    className,
    style,
    ...rest
  } = props;

  const parent = useContext(ThemeContext);
  const { locale, direction } = useLocale();

  const [modeState, setModeState] = useState<ThemeMode | undefined>(defaultMode);
  const [themeState, setThemeState] = useState<Theme | undefined>(() => (defaultTheme ? toTheme(defaultTheme) : undefined));
  const [densityState, setDensityState] = useState<Density | undefined>(defaultDensity);
  const [lookState, setLookState] = useState<Look | undefined>(defaultLook);
  const [persistenceError, setPersistenceError] = useState<ThemePersistenceError | null>(null);

  const mode: ThemeMode = modeProp ?? modeState ?? parent?.mode ?? 'system';
  const theme: Theme = themeProp ? toTheme(themeProp) : (themeState ?? parent?.theme ?? getPreset(DEFAULT_PRESET));
  const density: Density = densityProp ?? densityState ?? parent?.density ?? 'comfortable';
  const look: Look = lookProp ?? lookState ?? parent?.look ?? DEFAULT_LOOK;

  const systemScheme = useSyncExternalStore(subscribeScheme, getSchemeSnapshot, getServerScheme);
  const resolvedScheme: ResolvedScheme = mode === 'system' ? systemScheme : mode;

  const persistOpts = persistence === true ? {} : persistence || null;
  const storageKey = persistOpts?.key ?? DEFAULT_STORAGE_KEY;
  const persistKeysKey = (persistOpts?.keys ?? ['mode']).join(',');
  const persistKeys = persistKeysKey.split(',');
  const storageRef = useRef<ThemeStorage | null>(null);
  const enabled = persistOpts !== null;
  const customStorage = persistOpts?.storage;
  const getStorage = useCallback((): ThemeStorage | null => {
    if (!enabled) return null;
    if (customStorage) return customStorage;
    storageRef.current ??= createLocalStorageAdapter();
    return storageRef.current;
  }, [enabled, customStorage]);

  const reportError = useCallback(
    (error: ThemePersistenceError) => {
      setPersistenceError(error);
      onPersistenceError?.(error);
    },
    [onPersistenceError],
  );

  const latest = useRef({ mode, theme, density, look });
  useIsoLayoutEffect(() => {
    latest.current = { mode, theme, density, look };
  });

  const persist = useCallback(
    (patch: ThemePreferences) => {
      const storage = getStorage();
      if (!storage) return;
      const current = latest.current;
      const keys = persistKeysKey.split(',');
      const prefs: ThemePreferences = {};
      const next = { mode: current.mode, theme: current.theme.name, density: current.density, look: current.look, ...patch };
      if (keys.includes('mode')) prefs.mode = next.mode;
      if (keys.includes('theme')) prefs.theme = next.theme;
      if (keys.includes('density')) prefs.density = next.density;
      if (keys.includes('look')) prefs.look = next.look;
      try {
        storage.set(storageKey, serializePreferences(prefs));
        setPersistenceError(null);
      } catch (error) {
        reportError(new ThemePersistenceError('write', error));
      }
    },
    [getStorage, storageKey, persistKeysKey, reportError],
  );

  // Restore persisted preferences after mount (never during render, so SSR output is stable).
  const restored = useRef(false);
  useIsoLayoutEffect(() => {
    if (restored.current) return;
    restored.current = true;
    const storage = getStorage();
    if (!storage) return;
    let prefs: ThemePreferences;
    try {
      prefs = parsePreferences(storage.get(storageKey));
    } catch (error) {
      reportError(new ThemePersistenceError(error instanceof SyntaxError ? 'parse' : 'read', error));
      return;
    }
    if (persistKeys.includes('mode') && prefs.mode && modeProp === undefined) setModeState(prefs.mode);
    if (persistKeys.includes('density') && prefs.density && densityProp === undefined) setDensityState(prefs.density);
    if (persistKeys.includes('look') && prefs.look && lookProp === undefined) setLookState(prefs.look);
    if (persistKeys.includes('theme') && prefs.theme && themeProp === undefined) {
      const found = isPresetName(prefs.theme) ? getPreset(prefs.theme) : themes?.find((t) => t.name === prefs.theme);
      if (found) setThemeState(found);
    }
  });

  const setMode = useCallback(
    (next: ThemeMode) => {
      setModeState(next);
      onModeChange?.(next);
      persist({ mode: next });
    },
    [onModeChange, persist],
  );
  const setTheme = useCallback(
    (next: PresetName | Theme) => {
      const t = toTheme(next);
      setThemeState(t);
      onThemeChange?.(t);
      persist({ theme: t.name });
    },
    [onThemeChange, persist],
  );
  const setDensity = useCallback(
    (next: Density) => {
      setDensityState(next);
      onDensityChange?.(next);
      persist({ density: next });
    },
    [onDensityChange, persist],
  );
  const setLook = useCallback(
    (next: Look) => {
      setLookState(next);
      onLookChange?.(next);
      persist({ look: next });
    },
    [onLookChange, persist],
  );

  const inlineVars = useMemo<Record<string, string> | undefined>(
    () => (theme.kind === 'custom' && themeStrategy === 'inline' ? themeToStyle(theme) : undefined),
    [theme, themeStrategy],
  );
  const dataAttrs = useMemo(() => {
    const attrs: Record<string, string> = {
      [`data-${TOKEN_PREFIX}-theme`]: '',
      [`data-${TOKEN_PREFIX}-palette`]: theme.name,
      [`data-${TOKEN_PREFIX}-scheme`]: mode,
      [`data-${TOKEN_PREFIX}-resolved-scheme`]: resolvedScheme,
      [`data-${TOKEN_PREFIX}-density`]: density,
      [`data-${TOKEN_PREFIX}-look`]: look,
    };
    if (inlineVars) attrs[`data-${TOKEN_PREFIX}-palette-source`] = 'inline';
    return attrs;
  }, [theme.name, mode, resolvedScheme, density, look, inlineVars]);

  // Portal container: created lazily on the client, kept in sync with this provider.
  const [portalContainer, setPortalContainer] = useState<HTMLElement | null>(null);
  useIsoLayoutEffect(() => {
    const el = document.createElement('div');
    el.setAttribute(`data-${TOKEN_PREFIX}-portal`, '');
    el.className = styles.portal ?? '';
    document.body.appendChild(el);
    setPortalContainer(el);
    return () => {
      el.remove();
      setPortalContainer(null);
    };
  }, []);
  useIsoLayoutEffect(() => {
    if (!portalContainer) return;
    syncElement(portalContainer, dataAttrs, inlineVars, { lang: locale, dir: direction });
  }, [portalContainer, dataAttrs, inlineVars, locale, direction]);

  useIsoLayoutEffect(() => {
    if (!applyToDocument) return;
    const root = document.documentElement;
    const previous = new Map<string, string | null>();
    for (const name of Object.keys(dataAttrs)) previous.set(name, root.getAttribute(name));
    syncElement(root, dataAttrs, undefined, {});
    return () => {
      for (const [name, value] of previous) {
        if (value === null) root.removeAttribute(name);
        else root.setAttribute(name, value);
      }
    };
  }, [applyToDocument, dataAttrs]);

  const getContainer = useCallback(() => portalContainer ?? document.body, [portalContainer]);

  const value = useMemo<ThemeContextValue>(
    () => ({ mode, setMode, resolvedScheme, theme, setTheme, density, setDensity, look, setLook, persistenceError, portalContainer }),
    [mode, setMode, resolvedScheme, theme, setTheme, density, setDensity, look, setLook, persistenceError, portalContainer],
  );

  const rootClass = [styles.root, surface ? styles.surface : undefined, className].filter(Boolean).join(' ');
  const rootStyle: CSSProperties | undefined = inlineVars || style ? { ...inlineVars, ...style } : undefined;

  return (
    <ThemeContext.Provider value={value}>
      <UNSAFE_PortalProvider getContainer={getContainer}>
        <div {...rest} {...dataAttrs} ref={ref} className={rootClass} style={rootStyle}>
          {children}
        </div>
      </UNSAFE_PortalProvider>
    </ThemeContext.Provider>
  );
});

const appliedVars = new WeakMap<HTMLElement, string[]>();
function syncElement(
  el: HTMLElement,
  attrs: Record<string, string>,
  vars: Record<string, string> | undefined,
  extra: { lang?: string; dir?: string },
) {
  for (const name of [...el.getAttributeNames()]) {
    if (name.startsWith(`data-${TOKEN_PREFIX}-`) && name !== `data-${TOKEN_PREFIX}-portal` && !(name in attrs)) el.removeAttribute(name);
  }
  for (const [name, val] of Object.entries(attrs)) el.setAttribute(name, val);
  for (const prop of appliedVars.get(el) ?? []) el.style.removeProperty(prop);
  const props = vars ? Object.keys(vars) : [];
  for (const prop of props) el.style.setProperty(prop, vars?.[prop] ?? '');
  appliedVars.set(el, props);
  if (extra.lang) el.lang = extra.lang;
  if (extra.dir) el.dir = extra.dir;
}

/** Reads the nearest theme. Throws outside a ThemeProvider unless `optional` is set. */
export function useTheme(): ThemeContextValue;
export function useTheme(options: { optional: true }): ThemeContextValue | null;
export function useTheme(options?: { optional?: boolean }): ThemeContextValue | null {
  const ctx = useContext(ThemeContext);
  if (!ctx && !options?.optional) throw new Error('useTheme must be used inside <ThemeProvider>.');
  return ctx;
}

/** Container used by this provider for portalled content (null before mount/SSR). */
export function usePortalContainer(): HTMLElement | null {
  return useContext(ThemeContext)?.portalContainer ?? null;
}
